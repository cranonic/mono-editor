/** Modifier bitmasks (matches Monaco KeyMod). */
export const KeyMod = {
  CtrlCmd: 2048,
  Shift: 1024,
  Alt: 512,
  WinCtrl: 256,
  chord(firstPart: number, secondPart: number): number {
    return (firstPart | ((secondPart & 0xffff) << 16)) >>> 0;
  },
} as const;

